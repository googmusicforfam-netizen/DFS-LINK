function convertTemplatesToSlatePlayers(
  templates: PlayerTemplate[],
  sport: Sport,
  game: Game
): SlatePlayer[] {
  return templates.map((t, idx) => ({
    id: `sl-ply-${sport}-${t.team}-${idx}-${t.name.replace(/\s+/g, '').toLowerCase()}`,
    name: t.name,
    sport,
    team: t.team,
    teamName: t.teamName,
    opponent: t.opponent,
    position: t.pos,
    eligiblePositions: t.eligiblePositions,
    salaryDK: t.salaryDK,
    salaryFD: t.salaryFD,
    projectedPoints: t.proj,
    gameId: game.id,
    gameMatchup: `${game.awayTeam.abbreviation} @ ${game.homeTeam.abbreviation}`,
    gameTime: game.gameTime,
    isHome: t.isHome,
    spread: game.spread.text,
    overUnder: game.overUnder,
    impliedTeamTotal: t.isHome ? game.impliedHomeScore : game.impliedAwayScore,
    injuryStatus: t.injuryStatus || 'HEALTHY',
    injuryNote: t.injuryNote,
    isBeneficiary: t.isBeneficiary,
    beneficiaryInfo: t.beneficiaryInfo,
  }));
}

